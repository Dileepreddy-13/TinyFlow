"""
Core data models for the TinyFlow IoT packet aggregation simulation.
Explicit representation of sensor readings, packets, and adaptive decisions.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional


class ReadingPriority(int, Enum):
    """Priority levels for IoT sensor readings."""
    NORMAL = 1
    HIGH = 2
    CRITICAL = 3

    @property
    def label(self) -> str:
        return self.name

    @property
    def deadline_factor(self) -> float:
        """Urgency scale factor: higher priority means tighter delivery deadline."""
        if self == ReadingPriority.CRITICAL:
            return 0.4  # 40% of baseline deadline
        elif self == ReadingPriority.HIGH:
            return 0.7  # 70% of baseline deadline
        return 1.0     # standard deadline


class ReadingType(str, Enum):
    """Types of synthetic IoT sensor readings."""
    TEMPERATURE = "temperature"
    HUMIDITY = "humidity"
    SOIL_MOISTURE = "soil_moisture"


@dataclass(slots=True)
class SensorReading:
    """
    Individual sensor measurement generated by a virtual IoT sensor.
    
    Attributes:
        id: Unique identifier for the reading.
        sensor_id: Integer identifier of the originating sensor node.
        timestamp: Generation timestamp (simulation seconds).
        reading_type: Physical phenomenon measured.
        value: Numerical reading value.
        unit: Measurement unit (e.g. °C, %, %RH).
        priority: Urgency/priority level.
        deadline: Absolute simulation timestamp by which reading must reach receiver.
        payload_bytes: Wire byte size of this reading when serialized into packet.
    """
    id: str
    sensor_id: int
    timestamp: float
    reading_type: ReadingType
    value: float
    unit: str
    priority: ReadingPriority
    deadline: float
    payload_bytes: int = 14  # Standard compact IoT binary payload representation

    @property
    def age(self, current_time: float) -> float:
        return max(0.0, current_time - self.timestamp)

    def slack(self, current_time: float) -> float:
        """Time remaining until delivery deadline expires."""
        return self.deadline - current_time

    def is_expired(self, current_time: float) -> bool:
        return current_time > self.deadline


@dataclass
class Packet:
    """
    Simulated network packet traversing the link.
    Can contain a single reading (Immediate) or multiple batched readings (Fixed/Adaptive).
    
    Attributes:
        id: Unique packet identifier.
        sequence_number: Packet sequence number.
        creation_time: Timestamp when packet was assembled.
        readings: List of sensor readings encapsulated in the payload.
        header_bytes: Protocol header overhead (e.g., IEEE 802.15.4 MAC + 6LoWPAN / UDP).
        framing_bytes_per_reading: Metadata delimiter / offset overhead per batched reading.
        max_packet_size: Maximum Transmission Unit (MTU) limit.
        is_cross_traffic: True if packet represents competing background traffic.
        strategy_name: Name of aggregation strategy that produced the packet.
    """
    id: str
    sequence_number: int
    creation_time: float
    readings: List[SensorReading] = field(default_factory=list)
    header_bytes: int = 28
    framing_bytes_per_reading: int = 2
    max_packet_size: int = 128
    is_cross_traffic: bool = False
    strategy_name: str = "immediate"
    custom_payload_bytes: Optional[int] = None

    # Transmission state tracked by simulator
    transmission_start_time: Optional[float] = None
    transmission_end_time: Optional[float] = None
    delivery_time: Optional[float] = None
    was_dropped: bool = False
    drop_reason: Optional[str] = None

    @property
    def payload_bytes(self) -> int:
        if self.custom_payload_bytes is not None:
            return self.custom_payload_bytes
        if not self.readings:
            return 0
        raw_reading_bytes = sum(r.payload_bytes for r in self.readings)
        batch_framing = len(self.readings) * self.framing_bytes_per_reading
        return raw_reading_bytes + batch_framing

    @property
    def total_bytes(self) -> int:
        return self.header_bytes + self.payload_bytes

    @property
    def reading_count(self) -> int:
        return len(self.readings)

    @property
    def header_overhead_ratio(self) -> float:
        """Header bytes divided by total packet bytes."""
        total = self.total_bytes
        return (self.header_bytes / total) if total > 0 else 0.0

    def can_fit_reading(self, reading: SensorReading) -> bool:
        """Check if adding another reading would exceed MTU."""
        new_payload = self.payload_bytes + reading.payload_bytes + self.framing_bytes_per_reading
        return (self.header_bytes + new_payload) <= self.max_packet_size


class DecisionAction(str, Enum):
    """Action chosen by the aggregation policy."""
    TRANSMIT = "TRANSMIT"
    WAIT = "WAIT"
    DROP_EXPIRED = "DROP_EXPIRED"


class DecisionReasonCode(str, Enum):
    """Standardized decision reason codes for logging and analysis."""
    BUFFER_FULL_MTU = "BUFFER_FULL_MTU"
    DEADLINE_APPROACHING = "DEADLINE_APPROACHING"
    URGENT_PRIORITY_TRIGGER = "URGENT_PRIORITY_TRIGGER"
    MAX_WAIT_EXCEEDED = "MAX_WAIT_EXCEEDED"
    CONGESTION_FLUSH = "CONGESTION_FLUSH"
    BUFFER_ROOM_WAITING = "BUFFER_ROOM_WAITING"
    EMPTY_BUFFER = "EMPTY_BUFFER"
    SIMULATION_TERMINATION = "SIMULATION_TERMINATION"


@dataclass
class DecisionRecord:
    """
    Transparent record of a dynamic decision made by the Adaptive Aggregator.
    Every field is derived directly from genuine internal simulator state.
    """
    timestamp: float
    action: DecisionAction
    reason_code: DecisionReasonCode
    reason_text: str
    buffer_count: int
    buffer_bytes: int
    oldest_reading_age: float
    min_slack: float
    queue_occupancy: int
    estimated_queue_delay: float
    packet_id: Optional[str] = None
    readings_count: int = 0
